using System;
using UnityEngine;

public class TimerExample : MonoBehaviour
{
    private void Start()
    {
        // Пример 1: Написать число 5 спустя 5 секунд
        Timer timer1 = new Timer(
            5f,                  // Задержка перед началом
            0f,                  // Продолжительность (0, так как действие однократное)
            5f,                  // Частота действий (должно совпадать с задержкой)
            () => Debug.Log(5),  // Действие: вывод числа 5
            null                 // Завершение: ничего не нужно
        );
        timer1.Start();

        // Пример 2: Каждую секунду в течение 5 секунд писать единицу
        Timer timer2 = new Timer(
            0f,                  // Без задержки
            5f,                  // Длительность 5 секунд
            1f,                  // Частота действий 1 секунда
            () => Debug.Log(1),  // Действие: вывод числа 1
            () => Debug.Log("Completed") // Завершение: вывод сообщения о завершении
        );
        timer2.Start();
    }
}
